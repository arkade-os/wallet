#!/usr/bin/env node
/**
 * Applies `native.config.json` to the generated iOS and Android projects.
 *
 * /ios and /android are gitignored regenerable scaffold, so hand-edits inside
 * them do not survive `npx cap add`. This script is the committed replacement:
 * it runs after every `cap sync` (see the cap:sync package scripts) and is
 * idempotent, so re-running it — or running it against a freshly regenerated
 * project — converges on the same result.
 *
 * Android edits are delimited by BEGIN/END marker comments and replaced
 * wholesale on each run. iOS edits go through a real plist parse/serialize.
 *
 * Missing platform directories are skipped, not an error: a machine that only
 * has the Android toolchain still syncs cleanly.
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { parse as parsePlist, build as buildPlist } from 'plist'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const config = JSON.parse(readFileSync(join(root, 'native.config.json'), 'utf8'))

const changes = []

/**
 * Replaces the named marker block, or inserts it before the last `beforeTag`.
 * Each block needs its own `name` — a shared marker would make the second call
 * match and overwrite the first block instead of adding its own.
 */
const applyBlock = (source, { name, body, beforeTag, indent }) => {
  const begin = `<!-- BEGIN arkade ${name} (generated by scripts/cap-configure.mjs) -->`
  const end = `<!-- END arkade ${name} -->`
  const block = [`${indent}${begin}`, body, `${indent}${end}`].join('\n')
  const existing = new RegExp(`[ \\t]*${escapeRe(begin)}[\\s\\S]*?${escapeRe(end)}`)
  if (existing.test(source)) return source.replace(existing, block)
  const at = source.lastIndexOf(beforeTag)
  if (at === -1) throw new Error(`could not find ${beforeTag} to anchor the ${name} block`)
  return source.slice(0, at) + block + '\n' + source.slice(at)
}

const escapeRe = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')

const edit = (path, fn) => {
  const full = join(root, path)
  if (!existsSync(full)) return false
  const before = readFileSync(full, 'utf8')
  const after = fn(before)
  if (after !== before) {
    writeFileSync(full, after)
    changes.push(path)
  }
  return true
}

// --- iOS --------------------------------------------------------------------

const configureIos = () => {
  const present = edit('ios/App/App/Info.plist', (source) => {
    const parsed = parsePlist(source)
    Object.assign(parsed, config.ios.infoPlist)

    // Custom URL scheme (arkade://). Registered under the bundle ID as the URL
    // type name so re-runs replace this entry rather than appending a duplicate.
    const urlTypeName = 'money.arkade.app.scheme'
    const urlTypes = (parsed.CFBundleURLTypes ?? []).filter((t) => t.CFBundleURLName !== urlTypeName)
    urlTypes.push({ CFBundleURLName: urlTypeName, CFBundleURLSchemes: [config.urlScheme] })
    parsed.CFBundleURLTypes = urlTypes

    return buildPlist(parsed) + '\n'
  })

  if (!present) return console.log('  ios/  not generated — skipped')

  // Universal Links need an entitlements file rather than a plist key. Only
  // written when explicitly enabled: an applinks entitlement whose capability
  // is not enabled on the Apple app ID fails the build outright.
  if (config.deepLinkDomains.enabled) {
    const domains = config.deepLinkDomains.hosts.map((h) => `applinks:${h}`)
    const entitlements = buildPlist({ 'com.apple.developer.associated-domains': domains }) + '\n'
    const path = 'ios/App/App/App.entitlements'
    const full = join(root, path)
    if (!existsSync(full) || readFileSync(full, 'utf8') !== entitlements) {
      writeFileSync(full, entitlements)
      changes.push(path)
      console.log('  ios/  associated domains written — enable the capability on the Apple app ID')
    }
  }
}

// --- Android ----------------------------------------------------------------

const configureAndroid = () => {
  const present = edit('android/app/src/main/AndroidManifest.xml', (source) => {
    let out = source

    // Lock the launcher activity to portrait, matching the iOS plist above.
    const orientation = `android:screenOrientation="${config.android.screenOrientation}"`
    out = out.includes('android:screenOrientation=')
      ? out.replace(/android:screenOrientation="[^"]*"/, orientation)
      : out.replace('android:name=".MainActivity"', `android:name=".MainActivity"\n            ${orientation}`)

    // Deep links, inside the launcher activity. The custom scheme always
    // applies; https App Links only once the domain files are hosted and
    // verified, since an unverified filter shows a disambiguation chooser.
    const filters = [
      `            <intent-filter>`,
      `                <action android:name="android.intent.action.VIEW" />`,
      `                <category android:name="android.intent.category.DEFAULT" />`,
      `                <category android:name="android.intent.category.BROWSABLE" />`,
      `                <data android:scheme="${config.urlScheme}" />`,
      `            </intent-filter>`,
    ]
    if (config.deepLinkDomains.enabled) {
      for (const host of config.deepLinkDomains.hosts) {
        filters.push(
          `            <intent-filter android:autoVerify="true">`,
          `                <action android:name="android.intent.action.VIEW" />`,
          `                <category android:name="android.intent.category.DEFAULT" />`,
          `                <category android:name="android.intent.category.BROWSABLE" />`,
          `                <data android:scheme="https" android:host="${host}" />`,
          `            </intent-filter>`,
        )
      }
    }
    out = applyBlock(out, {
      name: 'deep links',
      body: filters.join('\n'),
      beforeTag: '        </activity>',
      indent: '            ',
    })

    // Permissions, at manifest level.
    const permissions = config.android.permissions
      .map((name) => `    <uses-permission android:name="${name}" />`)
      .join('\n')
    return applyBlock(out, { name: 'permissions', body: permissions, beforeTag: '</manifest>', indent: '    ' })
  })

  if (!present) return console.log('  android/  not generated — skipped')

  edit('android/variables.gradle', (source) =>
    Object.entries(config.android.variables).reduce(
      (out, [key, value]) => out.replace(new RegExp(`${key} = \\d+`), `${key} = ${value}`),
      source,
    ),
  )

  // Capacitor defaults custom_url_scheme to the package name; point it at ours
  // so the plugin's own scheme handling agrees with the manifest above.
  edit('android/app/src/main/res/values/strings.xml', (source) =>
    source.replace(
      /(<string name="custom_url_scheme">)[^<]*(<\/string>)/,
      `$1${config.urlScheme}$2`,
    ),
  )
}

configureIos()
configureAndroid()

console.log(changes.length ? `native config applied:\n  ${changes.join('\n  ')}` : 'native config already up to date')
